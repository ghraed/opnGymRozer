CREATE TABLE member_subscriptions (
  id VARCHAR(64) PRIMARY KEY,
  member_id VARCHAR(64) NULL,
  member_name VARCHAR(80) NOT NULL,
  plan_id VARCHAR(64) NULL,
  plan_name VARCHAR(80) NOT NULL,
  cycle ENUM('monthly','quarterly','yearly') NOT NULL,
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  price DECIMAL(12,2) NOT NULL,
  currency ENUM('USD','LBP') NOT NULL,
  notes VARCHAR(1000) NOT NULL DEFAULT '',
  request_key VARCHAR(64) NOT NULL UNIQUE,
  request_hash CHAR(64) NOT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  cancelled_at TIMESTAMP(3) NULL,
  cancellation_reason VARCHAR(500) NULL,
  created_by VARCHAR(64) NULL,
  cancelled_by VARCHAR(64) NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT fk_subscription_member FOREIGN KEY (member_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_subscription_plan FOREIGN KEY (plan_id) REFERENCES membership_plans(id) ON DELETE SET NULL,
  CONSTRAINT fk_subscription_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_subscription_canceller FOREIGN KEY (cancelled_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT chk_subscription_dates CHECK (ends_on > starts_on),
  CONSTRAINT chk_subscription_price CHECK (price >= 0),
  INDEX idx_subscription_member_dates (member_id, starts_on, ends_on),
  INDEX idx_subscription_status (cancelled_at, ends_on, starts_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
